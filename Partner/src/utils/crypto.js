'use strict';

const crypto = require('crypto');

const ALGORITHM = 'aes-256-gcm';
const IV_LENGTH = 16;

/**
 * Derives a consistent 32-byte key from environment secret.
 *
 * @returns {Buffer}
 */
function getEncryptionKey() {
  const secret = process.env.ENCRYPTION_KEY
    || process.env.CASHFREE_SECRET_KEY
    || 'gongo-default-bank-encryption-key-32b';
  return crypto.createHash('sha256').update(secret).digest();
}

/**
 * Encrypts sensitive plain text using AES-256-GCM.
 * Output format: `<iv_hex>:<auth_tag_hex>:<cipher_hex>`
 *
 * @param {string} text
 * @returns {string}
 */
function encrypt(text) {
  if (!text) return '';
  const key = getEncryptionKey();
  const iv = crypto.randomBytes(IV_LENGTH);
  const cipher = crypto.createCipheriv(ALGORITHM, key, iv);

  let encrypted = cipher.update(String(text), 'utf8', 'hex');
  encrypted += cipher.final('hex');

  const authTag = cipher.getAuthTag().toString('hex');
  return `${iv.toString('hex')}:${authTag}:${encrypted}`;
}

/**
 * Decrypts cipher text generated by `encrypt`.
 *
 * @param {string} cipherText
 * @returns {string}
 */
function decrypt(cipherText) {
  if (!cipherText) return '';
  const parts = String(cipherText).split(':');
  if (parts.length !== 3) {
    throw new Error('Invalid cipher text format');
  }

  const [ivHex, authTagHex, encryptedHex] = parts;
  const key = getEncryptionKey();
  const iv = Buffer.from(ivHex, 'hex');
  const authTag = Buffer.from(authTagHex, 'hex');

  const decipher = crypto.createDecipheriv(ALGORITHM, key, iv);
  decipher.setAuthTag(authTag);

  try {
    let decrypted = decipher.update(encryptedHex, 'hex', 'utf8');
    decrypted += decipher.final('utf8');
    return decrypted;
  } catch (err) {
    throw new Error('Failed to decrypt data: authentication tag mismatch or corrupted payload');
  }
}

module.exports = {
  encrypt,
  decrypt,
};
